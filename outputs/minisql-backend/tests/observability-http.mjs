import { spawn } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { once } from 'node:events';
import assert from 'node:assert/strict';
const server = spawn(process.execPath, [fileURLToPath(new URL('../scripts/database-bridge.mjs', import.meta.url))], {
  env: { ...process.env, PORT: '0', MINISQL_DB: join(mkdtempSync(join(tmpdir(), 'minisql-http-stats-')), 'db.pages') },
  windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'],
});
const exited = once(server, 'exit');
let errors = '', url, session, readerSession, writerSession;
server.stderr.on('data', chunk => { errors += chunk; });
const timer = setTimeout(() => server.kill(), 45000);
async function request(path, sql, method = 'POST', user) {
  const headers = method === 'POST' ? { 'Content-Type': 'application/json' } : {};
  if (user) headers['X-MiniSQL-User'] = user;
  const response = await fetch(url + path, { method, headers, signal: AbortSignal.timeout(10000),
    ...(method === 'POST' ? { body: JSON.stringify({ sql }) } : {}) });
  return { status: response.status, data: await response.json() };
}
try {
  url = await new Promise((resolve, reject) => {
    let output = '';
    server.stdout.on('data', chunk => { output += chunk; const match = output.match(/http:\/\/127\.0\.0\.1:\d+\/api/); if (match) resolve(match[0]); });
    server.once('error', reject);
    server.once('exit', () => reject(new Error(errors || 'Server exited before readiness')));
  });
  const opened = await request('/sessions');
  assert.equal(opened.status, 201);
  session = `/sessions/${opened.data.sessionId}`;
  assert.equal((await request(session + '/execute', 'CREATE TABLE t(id INT); INSERT INTO t VALUES(1),(2);')).status, 200);
  const committedStats = (await request(session + '/catalog', undefined, 'GET')).data.buffer;
  const tableStats = await request(session + '/statistics', undefined, 'GET');
  assert.equal(tableStats.status, 200);
  assert.equal(tableStats.data.tables[0].rowCount, 2);
  assert.equal(tableStats.data.tables[0].columns.length, 1);
  assert.ok(committedStats.diskWrites > 0, 'Committed pages must count as database-file writes');
  assert.equal(committedStats.diskScope, 'database-file-pages-including-header');
  const analyzed = await request(session + '/execute', 'EXPLAIN ANALYZE SELECT * FROM t;');
  assert.equal(analyzed.status, 200);
  assert.equal(analyzed.data.executionStats.actualRows, 2);
  assert.ok(analyzed.data.plan.length > 0);
  assert.equal(analyzed.data.executionStats.nodeStatisticsAvailable, true);
  assert.ok(analyzed.data.executionStats.nodeStatistics.length > 0);
  assert.equal((await request(session + '/execute', 'EXPLAIN ANALYZE DELETE FROM t;')).status, 422);
  assert.deepEqual((await request(session + '/execute', 'SELECT * FROM t ORDER BY id;')).data.rows, [[1],[2]]);
  assert.equal((await request(session + '/buffer', 'FIFO')).data.buffer.policy, 'FIFO');
  const resetStats = (await request(session + '/buffer', 'RESET')).data.buffer;
  assert.equal(resetStats.hits, 0);
  assert.equal(resetStats.diskWrites, 0);
  assert.equal(resetStats.diskReads, 0);
  await request(session + '/execute', 'BEGIN;');
  assert.equal((await request(session + '/buffer', 'LRU')).status, 422);
  assert.equal((await request(session + '/catalog', undefined, 'GET')).data.transactionState, 'ACTIVE');
  await request(session + '/execute', 'ROLLBACK;');
  assert.equal((await request(session + '/buffer', 'LRU')).data.buffer.policy, 'LRU');
  const capabilities = await request('/capabilities', undefined, 'GET');
  assert.equal(capabilities.data.floatColumns, true);
  assert.equal(capabilities.data.floatEncoding, 'json-number-finite-only');
  assert.ok(capabilities.data.capabilities.includes('float'));
  assert.ok(capabilities.data.capabilities.includes('checkpoint'));
  assert.equal(capabilities.data.externalSort, true);
  assert.equal(capabilities.data.sortSpill, true);
  assert.equal(capabilities.data.sortSpillEncoding, 'jsonl');
  assert.equal(capabilities.data.sortArtifactIdentity, 'session-query-sort');
  assert.equal(capabilities.data.sortChecksum, 'fnv1a64');
  assert.equal(capabilities.data.externalAggregate, true);
  assert.equal(capabilities.data.aggregateSpill, true);
  assert.equal(capabilities.data.aggregateSpillEncoding, 'jsonl');
  assert.ok(capabilities.data.capabilities.includes('externalAggregate'));
  assert.ok(capabilities.data.capabilities.includes('aggregateSpill'));
  assert.equal(capabilities.data.cancellation, true);
  assert.equal(capabilities.data.cancellationMode, 'cancel-file');
  assert.equal(capabilities.data.cancellationScope, 'request-and-session');
  assert.equal(capabilities.data.cancelledErrorCode, 5002);
  assert.ok(capabilities.data.capabilities.includes('cancellation'));
  assert.equal(capabilities.data.autoCheckpoint, true);
  assert.ok(capabilities.data.capabilities.includes('autoCheckpoint'));
  assert.equal(typeof capabilities.data.maxResultRows, 'number');
  assert.equal(capabilities.data.backupManifestVersion, 2);
  assert.equal(capabilities.data.backupMigration, 'v1-to-v2');
  assert.ok(capabilities.data.capabilities.includes('backupMigration'));
  assert.ok(capabilities.data.capabilities.includes('externalSort'));
  assert.ok(capabilities.data.capabilities.includes('sortSpill'));
  assert.ok(capabilities.data.castTargets.includes('float'));
  assert.equal((await request(session + '/execute', "CREATE TABLE floats(v FLOAT); INSERT INTO floats VALUES(1e2);")).status, 200);
  assert.deepEqual((await request(session + '/execute', 'SELECT v FROM floats;')).data.rows, [[100]]);
  assert.deepEqual((await request(session + '/execute', 'SELECT v FROM floats WHERE v IN (SELECT v FROM floats);')).data.rows, [[100]]);
  assert.deepEqual((await request(session + '/execute', 'SELECT v FROM floats WHERE EXISTS (SELECT v FROM floats WHERE v=CAST(100 AS FLOAT));')).data.rows, [[100]]);
  assert.deepEqual((await request(session + '/execute', 'SELECT (SELECT v FROM floats LIMIT 1) FROM floats LIMIT 1;')).data.rows, [[100]]);
  assert.deepEqual((await request(session + '/execute', 'SELECT v FROM floats x WHERE EXISTS (SELECT v FROM floats WHERE v=CAST(x.v AS FLOAT));')).data.rows, [[100]]);
  const checkpoint = await request(session + '/execute', 'CHECKPOINT;');
  assert.equal(checkpoint.status, 200);
  assert.equal(checkpoint.data.results[0].kind, 'Checkpoint');
  const sessionDiagnostics = await request(session + '/diagnostics', 'SELECT missing FROM floats; SELECT * FROM missing;');
  assert.equal(sessionDiagnostics.status, 422);
  assert.equal(sessionDiagnostics.data.count, 2);
  assert.equal(sessionDiagnostics.data.diagnostics.every(item => item.stage === 'semantic'), true);
  readerSession = (await request('/sessions', undefined, 'POST', 'reader'));
  assert.equal(readerSession.status, 201);
  writerSession = (await request('/sessions', undefined, 'POST', 'writer'));
  assert.equal(writerSession.status, 201);
  assert.equal((await request(`/sessions/${readerSession.data.sessionId}/execute`, 'SELECT 1 FROM floats;', 'POST', 'reader')).status, 200);
  assert.equal((await request(`/sessions/${readerSession.data.sessionId}/execute`, 'INSERT INTO floats VALUES(200);', 'POST', 'reader')).status, 403);
  assert.equal((await request(`/sessions/${writerSession.data.sessionId}/execute`, 'INSERT INTO floats VALUES(200);', 'POST', 'writer')).status, 200);
  assert.equal((await request('/sessions', undefined, 'POST', 'unknown')).status, 403);
  const users = await request('/users', undefined, 'GET');
  assert.equal(users.status, 200);
  assert.equal(users.data.users.some(user => user.name === 'reader'), true);
  const audit = await request('/audit?limit=10', undefined, 'GET');
  assert.equal(audit.status, 200);
  assert.ok(audit.data.count > 0);
  assert.ok(audit.data.entries.every(entry => typeof entry.method === 'string' && typeof entry.path === 'string' && Number.isFinite(entry.durationMs)));
  console.log('42 observability HTTP checks passed');
} finally {
  if (url && session) await request(session + '/close').catch(() => {});
  if (url && readerSession?.data?.sessionId) await request(`/sessions/${readerSession.data.sessionId}/close`, undefined, 'POST', 'reader').catch(() => {});
  if (url && writerSession?.data?.sessionId) await request(`/sessions/${writerSession.data.sessionId}/close`, undefined, 'POST', 'writer').catch(() => {});
  server.kill();
  await exited;
  clearTimeout(timer);
}
