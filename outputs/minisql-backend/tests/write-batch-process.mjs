import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const executable = fileURLToPath(new URL('../bin/minisql_write_batch_contract.exe', import.meta.url));
const run = args => spawnSync(executable, args, {encoding:'utf8', windowsHide:true, timeout:10000});
const fixture = run([]);
assert.equal(fixture.status, 0, fixture.stderr);
const directory = fixture.stdout.match(/Evidence: (.+)/)?.[1].trim();
assert.ok(directory, fixture.stdout);
const path = join(directory, 'pages.db');
const before = readFileSync(path);
const crashed = run(['--crash',path]);
assert.equal(crashed.status, 73, crashed.stderr);
assert.deepEqual(readFileSync(path), before);
const reopened = run(['--read',path]);
assert.equal(reopened.status, 0, reopened.stderr);
assert.match(reopened.stdout, /Recovered base fixture/);
console.log('24 write-batch contracts and process-exit/reopen checks passed');
